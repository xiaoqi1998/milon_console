// goType maps an IDL type to a Go type for the builtin cases, used as the
// fallback of goReturnType.
func goType(idlType string, imp *importSet) string {
	t := strings.TrimSpace(idlType)
	if inner, ok := wrappedInner(t, "vec"); ok {
		return "[]" + goType(inner, imp)
	}
	if inner, ok := wrappedInner(t, "option"); ok {
		return "*" + goType(inner, imp)
	}
	if strings.HasPrefix(t, "map<") && strings.HasSuffix(t, ">") {
		parts := splitTopLevel(t[4 : len(t)-1])
		if len(parts) == 2 {
			return "map[" + goType(parts[0], imp) + "]" + goType(parts[1], imp)
		}
	}
	if strings.HasPrefix(t, "tuple<") && strings.HasSuffix(t, ">") {
		return "[]any"
	}
	switch t {
	case "Address", "Signer", "AnySigner":
		imp.crypto = true
		return "*crypto.Address"
	case "PublicKey":
		imp.crypto = true
		return "*crypto.PublicKey"
	case "String", "string":
		return "string"
	case "bool", "boolean":
		return "bool"
	case "u8":
		return "uint8"
	case "u16":
		return "uint16"
	case "u32":
		return "uint32"
	case "u64", "Bitmap64", "Amount", "Epoch":
		return "uint64"
	case "u128":
		imp.big = true
		return "*big.Int"
	case "i8":
		return "int8"
	case "i16":
		return "int16"
	case "i32":
		return "int32"
	case "i64":
		return "int64"
	case "bytes":
		return "[]byte"
	case "B96":
		return "[12]byte"
	case "B144":
		return "[18]byte"
	case "B160":
		return "[20]byte"
	case "B256":
		return "[32]byte"
	default:
		// Unknown IDL type: fall back to any.
		return "any"
	}
}

func wrappedInner(t, wrapper string) (string, bool) {
	prefix := wrapper + "<"
	if strings.HasPrefix(t, prefix) && strings.HasSuffix(t, ">") {
		return t[len(prefix) : len(t)-1], true
	}
	return "", false
}

// splitTopLevel splits s by top-level commas (ignores nested <>).
func splitTopLevel(s string) []string {
	var parts []string
	depth := 0
	start := 0
	for i, r := range s {
		switch r {
		case '<':
			depth++
		case '>':
			depth--
		case ',':
			if depth == 0 {
				parts = append(parts, strings.TrimSpace(s[start:i]))
				start = i + 1
			}
		}
	}
	parts = append(parts, strings.TrimSpace(s[start:]))
	return parts
}

var goKeywords = map[string]bool{
	"break": true, "default": true, "func": true, "interface": true, "select": true,
	"case": true, "defer": true, "go": true, "map": true, "struct": true,
	"chan": true, "else": true, "goto": true, "package": true, "switch": true,
	"const": true, "fallthrough": true, "if": true, "range": true, "type": true,
	"continue": true, "for": true, "import": true, "return": true, "var": true,
}

func goParamName(name string) string {
	if goKeywords[name] {
		return name + "_"
	}
	return name
}

func pascal(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}
